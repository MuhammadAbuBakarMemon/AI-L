"""
Data Types to store a collection in Python 
1- List
2- Tuple
3- Set
4- Range 
5- Dictionary

"""

list_data = [10, 20, 30, 40, 50, 'green']
tuple_data = (10, 20, 30, 'Abu Bakar')
set_data = {'abu bakar', 'ali', 'fatima', 30, 11.05}
range_data = range(1, 11)

print('List Data: ', list_data)
print('Tuple Data: ', tuple_data)
print('Set Data: ', set_data)
print('Range Data: ', range_data)